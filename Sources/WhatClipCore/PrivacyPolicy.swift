import Foundation

public enum CaptureDecision: Sendable, Equatable {
    case capture
    /// Keep it, but remove it automatically after `seconds` (it looks like a secret).
    case captureExpiring(seconds: TimeInterval, because: [SecretKind])
    case skip(Reason)

    public enum Reason: String, Sendable, Equatable { case paused, ignoreNext, concealed, transient, autoGenerated, excludedApp, empty, tooLarge, secret }
}

public enum PasteboardMarker {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
}

public enum SecretAction: String, Sendable, Codable, CaseIterable { case skip, expire, keep }

public struct PrivacyPolicy: Sendable {
    public var paused = false
    public var ignoreNextCopy = false
    public var excludedBundleIDs: Set<String> = []
    /// Copies whose text matches one of these regular expressions are never recorded.
    public var ignoredPatterns = IgnorePatterns([])
    /// Pasteboard types that, when present, mean the copy is not recorded.
    public var ignoredTypes: Set<String> = []
    public var maxCharacters = 1_000_000
    public var secretAction: SecretAction = .expire
    public var secretLifetime: TimeInterval = 60

    public init() {}

    /// Decide what to do with one clipboard change. `types` are the raw pasteboard type identifiers present.
    /// `ignoreNextCopy` is consumed by the caller after a `.skip(.ignoreNext)` result.
    public func decide(text: String, types: [String], sourceBundleID: String?) -> CaptureDecision {
        if paused { return .skip(.paused) }
        if ignoreNextCopy { return .skip(.ignoreNext) }
        if types.contains(PasteboardMarker.concealed) { return .skip(.concealed) }
        if types.contains(PasteboardMarker.transient) { return .skip(.transient) }
        if types.contains(PasteboardMarker.autoGenerated) { return .skip(.autoGenerated) }
        if let id = sourceBundleID, excludedBundleIDs.contains(id) { return .skip(.excludedApp) }
        if types.contains(where: { ignoredTypes.contains($0) }) { return .skip(.concealed) }
        if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .skip(.empty) }
        if ignoredPatterns.ignores(text) { return .skip(.excludedApp) }
        if text.count > maxCharacters { return .skip(.tooLarge) }
        let found = SecretDetector.scan(text).map(\.kind)
        if !found.isEmpty {
            switch secretAction {
            case .skip: return .skip(.secret)
            case .expire: return .captureExpiring(seconds: secretLifetime, because: found)
            case .keep: return .capture
            }
        }
        return .capture
    }
}
